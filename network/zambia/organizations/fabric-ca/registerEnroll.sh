#!/usr/bin/env bash

# Registers and enrols users who carry a "role" attribute in their certificate (read by the chaincode).
# Usage: registerRoleUsers <org> <ca-port> name:role [name:role ...]
# Passwords follow the local test pattern <name>pw and only work against this development CA.
function registerRoleUsers() {
  local org=$1 port=$2
  shift 2
  local tls="${PWD}/organizations/fabric-ca/${org}/ca-cert.pem"
  local base="${PWD}/organizations/peerOrganizations/${org}.example.com"
  for entry in "$@"; do
    local name=${entry%%:*} role=${entry##*:}
    infoln "Registering ${name} with role ${role}"
    set -x
    fabric-ca-client register --caname "ca-${org}" --id.name "${name}" --id.secret "${name}pw" --id.type client \
      --id.attrs "role=${role}:ecert" --tls.certfiles "${tls}"
    fabric-ca-client enroll -u "https://${name}:${name}pw@localhost:${port}" --caname "ca-${org}" \
      --enrollment.attrs "role" -M "${base}/users/${name}@${org}.example.com/msp" --tls.certfiles "${tls}"
    { set +x; } 2>/dev/null
    cp "${base}/msp/config.yaml" "${base}/users/${name}@${org}.example.com/msp/config.yaml"
  done
}


function createZPPA() {
  infoln "Enrolling the CA admin"
  mkdir -p organizations/peerOrganizations/zppa.example.com/

  export FABRIC_CA_CLIENT_HOME=${PWD}/organizations/peerOrganizations/zppa.example.com/

  set -x
  fabric-ca-client enroll -u https://admin:adminpw@localhost:7054 --caname ca-zppa --tls.certfiles "${PWD}/organizations/fabric-ca/zppa/ca-cert.pem"
  { set +x; } 2>/dev/null

  echo 'NodeOUs:
  Enable: true
  ClientOUIdentifier:
    Certificate: cacerts/localhost-7054-ca-zppa.pem
    OrganizationalUnitIdentifier: client
  PeerOUIdentifier:
    Certificate: cacerts/localhost-7054-ca-zppa.pem
    OrganizationalUnitIdentifier: peer
  AdminOUIdentifier:
    Certificate: cacerts/localhost-7054-ca-zppa.pem
    OrganizationalUnitIdentifier: admin
  OrdererOUIdentifier:
    Certificate: cacerts/localhost-7054-ca-zppa.pem
    OrganizationalUnitIdentifier: orderer' > "${PWD}/organizations/peerOrganizations/zppa.example.com/msp/config.yaml"

  # Since the CA serves as both the organization CA and TLS CA, copy the org's root cert that was generated by CA startup into the org level ca and tlsca directories

  # Copy zppa's CA cert to zppa's /msp/tlscacerts directory (for use in the channel MSP definition)
  mkdir -p "${PWD}/organizations/peerOrganizations/zppa.example.com/msp/tlscacerts"
  cp "${PWD}/organizations/fabric-ca/zppa/ca-cert.pem" "${PWD}/organizations/peerOrganizations/zppa.example.com/msp/tlscacerts/ca.crt"

  # Copy zppa's CA cert to zppa's /tlsca directory (for use by clients)
  mkdir -p "${PWD}/organizations/peerOrganizations/zppa.example.com/tlsca"
  cp "${PWD}/organizations/fabric-ca/zppa/ca-cert.pem" "${PWD}/organizations/peerOrganizations/zppa.example.com/tlsca/tlsca.zppa.example.com-cert.pem"

  # Copy zppa's CA cert to zppa's /ca directory (for use by clients)
  mkdir -p "${PWD}/organizations/peerOrganizations/zppa.example.com/ca"
  cp "${PWD}/organizations/fabric-ca/zppa/ca-cert.pem" "${PWD}/organizations/peerOrganizations/zppa.example.com/ca/ca.zppa.example.com-cert.pem"

  infoln "Registering peer0"
  set -x
  fabric-ca-client register --caname ca-zppa --id.name peer0 --id.secret peer0pw --id.type peer --tls.certfiles "${PWD}/organizations/fabric-ca/zppa/ca-cert.pem"
  { set +x; } 2>/dev/null

  infoln "Registering user"
  set -x
  fabric-ca-client register --caname ca-zppa --id.name user1 --id.secret user1pw --id.type client --tls.certfiles "${PWD}/organizations/fabric-ca/zppa/ca-cert.pem"
  { set +x; } 2>/dev/null

  infoln "Registering the org admin"
  set -x
  fabric-ca-client register --caname ca-zppa --id.name zppaadmin --id.secret zppaadminpw --id.type admin --tls.certfiles "${PWD}/organizations/fabric-ca/zppa/ca-cert.pem"
  { set +x; } 2>/dev/null

  infoln "Generating the peer0 msp"
  set -x
  fabric-ca-client enroll -u https://peer0:peer0pw@localhost:7054 --caname ca-zppa -M "${PWD}/organizations/peerOrganizations/zppa.example.com/peers/peer0.zppa.example.com/msp" --tls.certfiles "${PWD}/organizations/fabric-ca/zppa/ca-cert.pem"
  { set +x; } 2>/dev/null

  cp "${PWD}/organizations/peerOrganizations/zppa.example.com/msp/config.yaml" "${PWD}/organizations/peerOrganizations/zppa.example.com/peers/peer0.zppa.example.com/msp/config.yaml"

  infoln "Generating the peer0-tls certificates, use --csr.hosts to specify Subject Alternative Names"
  set -x
  fabric-ca-client enroll -u https://peer0:peer0pw@localhost:7054 --caname ca-zppa -M "${PWD}/organizations/peerOrganizations/zppa.example.com/peers/peer0.zppa.example.com/tls" --enrollment.profile tls --csr.hosts peer0.zppa.example.com --csr.hosts localhost --tls.certfiles "${PWD}/organizations/fabric-ca/zppa/ca-cert.pem"
  { set +x; } 2>/dev/null

  # Copy the tls CA cert, server cert, server keystore to well known file names in the peer's tls directory that are referenced by peer startup config
  cp "${PWD}/organizations/peerOrganizations/zppa.example.com/peers/peer0.zppa.example.com/tls/tlscacerts/"* "${PWD}/organizations/peerOrganizations/zppa.example.com/peers/peer0.zppa.example.com/tls/ca.crt"
  cp "${PWD}/organizations/peerOrganizations/zppa.example.com/peers/peer0.zppa.example.com/tls/signcerts/"* "${PWD}/organizations/peerOrganizations/zppa.example.com/peers/peer0.zppa.example.com/tls/server.crt"
  cp "${PWD}/organizations/peerOrganizations/zppa.example.com/peers/peer0.zppa.example.com/tls/keystore/"* "${PWD}/organizations/peerOrganizations/zppa.example.com/peers/peer0.zppa.example.com/tls/server.key"

  infoln "Generating the user msp"
  set -x
  fabric-ca-client enroll -u https://user1:user1pw@localhost:7054 --caname ca-zppa -M "${PWD}/organizations/peerOrganizations/zppa.example.com/users/User1@zppa.example.com/msp" --tls.certfiles "${PWD}/organizations/fabric-ca/zppa/ca-cert.pem"
  { set +x; } 2>/dev/null

  cp "${PWD}/organizations/peerOrganizations/zppa.example.com/msp/config.yaml" "${PWD}/organizations/peerOrganizations/zppa.example.com/users/User1@zppa.example.com/msp/config.yaml"

  infoln "Generating the org admin msp"
  set -x
  fabric-ca-client enroll -u https://zppaadmin:zppaadminpw@localhost:7054 --caname ca-zppa -M "${PWD}/organizations/peerOrganizations/zppa.example.com/users/Admin@zppa.example.com/msp" --tls.certfiles "${PWD}/organizations/fabric-ca/zppa/ca-cert.pem"
  { set +x; } 2>/dev/null

  cp "${PWD}/organizations/peerOrganizations/zppa.example.com/msp/config.yaml" "${PWD}/organizations/peerOrganizations/zppa.example.com/users/Admin@zppa.example.com/msp/config.yaml"
  registerRoleUsers zppa 7054 officer1:officer committee1:committee committee2:committee inspector1:inspector inspector2:inspector gateway:gateway risk-service:ai regulator1:regulator
}

